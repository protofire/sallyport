//! Golden vectors shared by the Solidity tests, burn_member and b22: `fixtures/b22/vectors.json`.
//! Frozen: `B22_REGEN_VECTORS=1 cargo test -p bridge-core --test vectors` rewrites the file;
//! every normal run re-reads it and requires it to equal what this crate computes.
mod common;
use bridge_core::*;
use common::*;
use serde_json::{json, Value};

const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../fixtures/b22/vectors.json"
);

fn vectors() -> Value {
    let c = config();
    let cfg = config_id(&c);
    let sk = sk(&SEED);
    let b = bridge();
    let per_index: Vec<Value> = (0..2u64)
        .map(|i| {
            let nk = nk(&sk, &cfg, &TOK, D, i);
            let rk = rk(&sk, &cfg, &TOK, D, i);
            let r = recipient(&sk, &cfg, i).unwrap();
            json!({
                "index": i,
                "nk": hex(nk), "commitment": hex(commit(&nk)), "pnf": hex(pnf(&nk)),
                "n_pda": hex(n_pda(&b, &pnf(&nk))),
                "rk": hex(rk), "ek": hex(ek(&sk, &cfg, i).unwrap()), "recipient": hex(r),
                "burn_commitment": hex(burn_commitment(&rk, &r)), "nb": hex(burn_nullifier(&rk)),
                "leaf_pda": hex(leaf_pda(&b, &cfg, &TOK, D, i)),
            })
        })
        .collect();
    // burn tree with B_0, B_1 appended; journal for releasing B_0 against it
    let leaves: Vec<[u8; 32]> = (0..2u64)
        .map(|j| {
            burn_commitment(
                &rk(&sk, &cfg, &TOK, D, j),
                &recipient(&sk, &cfg, j).unwrap(),
            )
        })
        .collect();
    let mut f = Frontier::default();
    for l in &leaves {
        f.append(*l).unwrap();
    }
    let path = merkle_path(&leaves, 0);
    assert_eq!(merkle_root(leaves[0], 0, &path), Some(f.root()));
    let att = RootAttestation {
        chain_id: CHAIN_ID,
        vault: VAULT,
        config_id: cfg,
        token: TOK,
        denom: D,
        burn_root: f.root(),
        count: f.leaves,
        lez_height: LEZ_HEIGHT,
        lez_block_hash: LEZ_BLOCK_HASH,
    };
    let rk0 = rk(&sk, &cfg, &TOK, D, 0);
    let journal = ReleaseJournal {
        chain_id: CHAIN_ID,
        vault: VAULT,
        config_id: cfg,
        token: TOK,
        denom: D,
        burn_root: f.root(),
        nb: burn_nullifier(&rk0),
        recipient: recipient(&sk, &cfg, 0).unwrap(),
        relayer: RELAYER,
        fee: FEE,
    };
    json!({
        "_note": "RFP-022 golden vectors (docs/ARCHITECTURE.md §3.2). Generated by crates/bridge-core/tests/vectors.rs; hex without 0x; integers decimal.",
        "inputs": {
            "seed": hex(SEED), "token": hex(TOK), "denom": D.to_string(), "relayer": hex(RELAYER),
            "fee": FEE.to_string(), "lez_height": LEZ_HEIGHT, "lez_block_hash": hex(LEZ_BLOCK_HASH),
            "bridge_config": {
                "instance_id": hex(c.instance_id), "evm_chain_id": c.evm_chain_id,
                "genesis_validators_root": hex(c.genesis_validators_root), "vault": hex(c.vault),
                "deposit_topic0": hex(c.deposit_topic0), "zone_id": hex(c.zone_id),
                "bridge_program_id": hex(c.bridge_program_id), "admin": hex(c.admin.value()),
                "freezer": hex(c.freezer.value()), "salt": hex(c.salt),
            },
        },
        "constants": {
            "zone_id_local_standalone": hex(local_zone_id()),
            "deposit_topic0": hex(deposit_topic0()),
            "burn_root_accepted_topic0": hex(event_topic0(BURN_ROOT_ACCEPTED_EVENT)),
            "burn_root_revoked_topic0": hex(event_topic0(BURN_ROOT_REVOKED_EVENT)),
            "tag_root": hex(TAG_ROOT), "tag_rel": hex(TAG_REL),
            "frontier_borsh_len": borsh::to_vec(&Frontier::default()).unwrap().len(),
        },
        "config": {
            "borsh": hex(borsh::to_vec(&c).unwrap()), "config_id": hex(cfg),
            "config_pda": hex(config_pda(&b, &cfg)), "token_pda": hex(token_pda(&b, &cfg, &TOK)),
        },
        "sk": hex(sk),
        "per_index": per_index,
        "burn_tree": {
            "count": f.leaves, "root": hex(f.root()), "frontier_borsh": hex(borsh::to_vec(&f).unwrap()),
            "path_index0": path.iter().map(hex).collect::<Vec<_>>(),
        },
        "root_attestation": { "count": att.count, "burn_root": hex(att.burn_root), "digest": hex(att.digest()) },
        "release_journal": { "abi": hex(journal.encode()), "sha256": hex(journal.digest()) },
    })
}

#[test]
fn vectors_regen() {
    if std::env::var_os("B22_REGEN_VECTORS").is_some() {
        std::fs::write(
            PATH,
            serde_json::to_string_pretty(&vectors()).unwrap() + "\n",
        )
        .unwrap();
    }
}

#[test]
fn vectors_reread_equal() {
    let s = std::fs::read_to_string(PATH)
        .expect("fixtures/b22/vectors.json missing: run with B22_REGEN_VECTORS=1");
    let frozen: Value = serde_json::from_str(&s).unwrap();
    assert_eq!(frozen, vectors());
}
